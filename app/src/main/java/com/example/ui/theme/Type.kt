fun isUrduText(text: String): Boolean {
    return text.any { it in '\u0600'..'\u06FF' || it in '\u0750'..'\u077F' || it in '\uFB50'..'\uFDFF' || it in '\uFE70'..'\uFEFF' }
}

fun getFontFamilyForText(text: String, defaultFont: FontFamily = InterFontFamily): FontFamily {
    return if (isUrduText(text)) UrduNastaliqFontFamily else defaultFont
}

